import type { ReactNode } from 'react'
import type { Level } from '../lib/analysis/metrics'

export const LEVEL_COLOR: Record<Level | 'base' | 'info', string> = {
  ok: '#34d399',
  minor: '#fbbf24',
  major: '#fb7185',
  base: '#818cf8',
  info: '#3dd6ef',
}

export const LEVEL_LABEL: Record<Level, string> = { ok: 'On baseline', minor: 'Minor drift', major: 'Major drift' }

export function scoreColor(score: number) {
  if (!Number.isFinite(score)) return '#66748c'
  return score >= 85 ? LEVEL_COLOR.ok : score >= 65 ? LEVEL_COLOR.minor : LEVEL_COLOR.major
}

export function LevelChip({ level, small }: { level: Level | 'base'; small?: boolean }) {
  const color = LEVEL_COLOR[level]
  const label = level === 'base' ? 'Baseline' : level === 'ok' ? 'OK' : level === 'minor' ? 'Minor' : 'Major'
  return (
    <span className={`chip ${small ? '!px-1.5 !text-[10px]' : ''}`} style={{ color, borderColor: `${color}55`, background: `${color}14` }}>
      <span className="h-1.5 w-1.5 rounded-full" style={{ background: color }} />
      {label}
    </span>
  )
}

export function SourceBadge({ kind }: { kind: 'real' | 'synthetic' | 'upload' }) {
  if (kind === 'synthetic')
    return (
      <span className="chip border-violet-400/40 bg-violet-400/10 text-violet-300" title="Generated by a kinematic model with injected faults. Not a real person.">
        Simulated data
      </span>
    )
  return (
    <span className="chip border-emerald-400/40 bg-emerald-400/10 text-emerald-300" title="Measured from real video with MediaPipe Pose Landmarker.">
      {kind === 'upload' ? 'Your video · measured' : 'Real video · measured'}
    </span>
  )
}

export function Stat({ label, value, sub, color }: { label: string; value: ReactNode; sub?: ReactNode; color?: string }) {
  return (
    <div className="card card-pad !py-4">
      <div className="text-xs font-medium tracking-wide text-ink-300 uppercase">{label}</div>
      <div className="num mt-1 text-2xl font-semibold" style={color ? { color } : undefined}>
        {value}
      </div>
      {sub && <div className="mt-0.5 text-xs text-ink-400">{sub}</div>}
    </div>
  )
}

export function SectionTitle({ eyebrow, title, children }: { eyebrow?: string; title: ReactNode; children?: ReactNode }) {
  return (
    <div className="mb-6 max-w-3xl">
      {eyebrow && <div className="eyebrow mb-2">{eyebrow}</div>}
      <h2 className="text-2xl font-semibold tracking-tight text-white sm:text-3xl">{title}</h2>
      {children && <div className="mt-3 text-ink-300">{children}</div>}
    </div>
  )
}

export function ScoreRing({ score, size = 64, stroke = 6, label }: { score: number; size?: number; stroke?: number; label?: string }) {
  const r = (size - stroke) / 2
  const c = 2 * Math.PI * r
  const pct = Number.isFinite(score) ? Math.max(0, Math.min(100, score)) / 100 : 0
  const color = scoreColor(score)
  return (
    <div className="relative inline-flex items-center justify-center" style={{ width: size, height: size }}>
      <svg width={size} height={size} className="-rotate-90">
        <circle cx={size / 2} cy={size / 2} r={r} stroke="rgba(255,255,255,0.08)" strokeWidth={stroke} fill="none" />
        <circle
          cx={size / 2}
          cy={size / 2}
          r={r}
          stroke={color}
          strokeWidth={stroke}
          fill="none"
          strokeDasharray={c}
          strokeDashoffset={c * (1 - pct)}
          strokeLinecap="round"
          style={{ transition: 'stroke-dashoffset 600ms ease' }}
        />
      </svg>
      <div className="absolute inset-0 flex flex-col items-center justify-center">
        <span className="num font-semibold" style={{ fontSize: size * 0.3, color }}>
          {Number.isFinite(score) ? Math.round(score) : '—'}
        </span>
        {label && <span className="text-[9px] tracking-wider text-ink-400 uppercase">{label}</span>}
      </div>
    </div>
  )
}

export function Callout({ tone = 'info', title, children }: { tone?: 'info' | 'warn' | 'honest'; title?: string; children: ReactNode }) {
  const styles = {
    info: 'border-brand-400/25 bg-brand-400/[0.06] text-ink-200',
    warn: 'border-amber-400/30 bg-amber-400/[0.07] text-amber-100',
    honest: 'border-violet-400/30 bg-violet-400/[0.07] text-violet-100',
  }[tone]
  return (
    <div className={`rounded-xl border px-4 py-3 text-sm ${styles}`}>
      {title && <div className="mb-0.5 font-semibold text-white">{title}</div>}
      {children}
    </div>
  )
}

export function Tabs<T extends string>({ tabs, value, onChange }: { tabs: { id: T; label: string; hidden?: boolean }[]; value: T; onChange: (v: T) => void }) {
  return (
    <div className="flex gap-1 overflow-x-auto rounded-xl border border-white/[0.07] bg-ink-900/70 p-1">
      {tabs
        .filter((t) => !t.hidden)
        .map((t) => (
          <button
            key={t.id}
            onClick={() => onChange(t.id)}
            className={`rounded-lg px-3.5 py-2 text-sm font-medium whitespace-nowrap transition ${
              value === t.id ? 'bg-white/[0.09] text-white shadow-inner' : 'text-ink-300 hover:text-white'
            }`}
          >
            {t.label}
          </button>
        ))}
    </div>
  )
}
