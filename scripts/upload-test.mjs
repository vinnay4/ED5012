import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
p.on('pageerror', (e) => console.log('[pageerror]', e.message))
p.on('console', (m) => m.type() === 'error' && console.log('[console]', m.text()))
await p.goto('http://127.0.0.1:5173/#/analyze')
await p.waitForLoadState('networkidle')
await p.locator('input[type=file]').setInputFiles('public/samples/oblique-barbell-back-squat.mp4')
const t0 = Date.now()
await p.waitForTimeout(8000)
await p.screenshot({ path: '/tmp/up-progress.png' })
await p.getByText('Self-perception check').first().waitFor({ timeout: 240000 })
console.log('extracted in', ((Date.now() - t0) / 1000).toFixed(1), 's')
await p
  .getByRole('button', { name: /Skip and show results/ })
  .click()
  .catch(() => {})
await p.waitForTimeout(800)
await p.screenshot({ path: '/tmp/up-done.png', fullPage: true })
const txt = await p.locator('main').innerText()
console.log(txt.slice(0, 1200))
await b.close()
